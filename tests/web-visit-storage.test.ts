import assert from 'node:assert/strict';
import test from 'node:test';
import { addVisit, createInitialState, ensureDailyDoses, recordDose, removeVisit, selectHospital, setMedicationSchedule, setReminderOffsets, type AppState } from '../src/domain.ts';
import { photoFor } from './fixtures.ts';
import { mergeNewerVisitData, readWebState, writeWebState } from '../src/web-visit-storage.ts';

test('two stale tabs retain independent visit edits, and an unrelated later save cannot resurrect a deletion', async t => {
  const data = new Map<string, string>();
  const key = 'test-patient';
  const localStorage = {
    getItem: (name: string) => data.get(name) ?? null,
    setItem: (name: string, value: string) => { data.set(name, value); },
  };
  Object.defineProperty(globalThis, 'window', { configurable: true, value: { navigator, localStorage } });
  t.after(() => { Reflect.deleteProperty(globalThis, 'window'); });
  const now = new Date(2026, 10, 2, 8);
  const original = createInitialState(now);
  const first = { hospitalName: '시연 병원 A', date: '2026-11-04', time: '10:15' };
  const second = { hospitalName: '시연 병원 B', date: '2026-11-05', time: '12:37' };
  const [a, b] = await Promise.all([
    writeWebState(key, original, current => addVisit(current, first, now)),
    writeWebState(key, original, current => addVisit(current, second, now)),
  ]);
  const both = JSON.parse(data.get(key)!);
  assert.equal(both.visits.length, 2);
  const firstId = a.visits.find(visit => visit.hospitalName === first.hospitalName)!.id;
  const removed = await writeWebState(key, a, current => removeVisit(current, firstId, now));
  assert.deepEqual(removed.visits.map(visit => visit.hospitalName), [second.hospitalName]);

  const unrelated = setReminderOffsets(b, 'medication', [17]);
  const final = await writeWebState(key, unrelated);
  assert.deepEqual(final.visits, removed.visits);
  assert.equal(final.visitsRevision, removed.visitsRevision);
  assert.deepEqual(final.reminders.medicationMinutesBefore, [17]);
  assert.deepEqual(mergeNewerVisitData(b, removed).visits, removed.visits);
  assert.equal(mergeNewerVisitData(final, a), final);
});

test('changing the preferred clinic in one tab preserves a visit booked for another clinic', () => {
  const now = new Date(2026, 10, 2, 8);
  const original = selectHospital(createInitialState(now), '기존 병원', '0212345678', now);
  const changed = selectHospital(original, '새 병원', '', now);
  const booked = addVisit(original, { hospitalName: '기존 병원', date: '2026-11-04', time: '14:30' }, now);
  for (const merged of [mergeNewerVisitData(booked, changed), mergeNewerVisitData(changed, booked)]) {
    assert.deepEqual(merged.visits, booked.visits);
    assert.deepEqual(merged.hospitalContact, changed.hospitalContact);
    assert.deepEqual(merged.otherHospitalContacts, [original.hospitalContact]);
    assert.equal(mergeNewerVisitData(merged, original), merged);
  }
});

function fakeBrowserStorage(t: { after: (cleanup: () => void) => void }) {
  const data = new Map<string, string>();
  const localStorage = {
    getItem: (name: string) => data.get(name) ?? null,
    setItem: (name: string, value: string) => { data.set(name, value); },
  };
  Object.defineProperty(globalThis, 'window', { configurable: true, value: { navigator, localStorage } });
  t.after(() => { Reflect.deleteProperty(globalThis, 'window'); });
}

const statusOf = (state: AppState, id: string) => state.doses.find(dose => dose.id === id)?.status;

test('a dose recorded in one tab survives a stale tab, reaches it, and cannot be recorded twice or revived after undo', async t => {
  fakeBrowserStorage(t);
  const key = 'test-patient-doses';
  const evening = new Date(2026, 10, 13, 19, 5);
  const original = await writeWebState(key, createInitialState(new Date(2026, 10, 13, 7)));
  const dose = original.doses[original.doses.length - 1];
  const recorded = await writeWebState(key, original, current => recordDose(current, dose.id, true, evening, photoFor(evening)));
  assert.equal(statusOf(recorded, dose.id), 'taken');

  const stale = await writeWebState(key, setReminderOffsets(original, 'medication', [17]));
  assert.equal(statusOf(stale, dose.id), 'taken');
  assert.deepEqual(stale.reminders.medicationMinutesBefore, [17]);
  assert.equal(statusOf(mergeNewerVisitData(original, recorded), dose.id), 'taken');
  await assert.rejects(writeWebState(key, original, current => {
    if (statusOf(current, dose.id) !== 'pending') throw new Error('already recorded');
    return recordDose(current, dose.id, true, evening, photoFor(evening));
  }), /already recorded/);

  const undone = await writeWebState(key, stale, current => recordDose(current, dose.id, false, new Date(evening.getTime() + 60_000)));
  assert.equal(statusOf(undone, dose.id), 'pending');
  assert.equal(statusOf(await writeWebState(key, setReminderOffsets(stale, 'medication', [30])), dose.id), 'pending');
});

test('a new day generated by a stale tab is kept next to a dose recorded in another tab', async t => {
  fakeBrowserStorage(t);
  const key = 'test-patient-midnight';
  const lateEvening = new Date(2026, 10, 12, 19, 5);
  const yesterday = await writeWebState(key, createInitialState(new Date(2026, 10, 12, 7)));
  const dose = yesterday.doses[yesterday.doses.length - 1];
  await writeWebState(key, yesterday, current => recordDose(current, dose.id, true, lateEvening, photoFor(lateEvening)));
  const afterMidnight = await writeWebState(key, ensureDailyDoses(yesterday, new Date(2026, 10, 13, 0, 1)));
  assert.equal(statusOf(afterMidnight, dose.id), 'taken');
  assert.ok(afterMidnight.doses.some(item => item.date === '2026-11-13'));
});

test('a tab back from the background catches up first, so its schedule change keeps a record made in another tab', async t => {
  fakeBrowserStorage(t);
  const key = 'test-patient-resume';
  const evening = new Date(2026, 10, 13, 19, 5);
  const frozen = await writeWebState(key, createInitialState(new Date(2026, 10, 13, 7)));
  const dose = frozen.doses[frozen.doses.length - 1];
  await writeWebState(key, frozen, current => recordDose(current, dose.id, true, evening, photoFor(evening)));
  const caughtUp = mergeNewerVisitData(frozen, readWebState(key)!);
  assert.equal(statusOf(caughtUp, dose.id), 'taken');
  const later = new Date(evening.getTime() + 60_000);
  const rescheduled = await writeWebState(key, setMedicationSchedule(caughtUp, { frequency: 'once', times: ['21:00'] }, later));
  assert.equal(statusOf(rescheduled, dose.id), 'taken');
  assert.deepEqual(rescheduled.medicationSchedule, { frequency: 'once', times: ['21:00'] });
  assert.equal(readWebState('missing-key'), null);
  window.localStorage.setItem('broken-key', '{');
  assert.equal(readWebState('broken-key'), null);
});
